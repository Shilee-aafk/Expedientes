-- ─── Código automático EXP-001-2026 (correlativo por año) ────────────
create or replace function public.siguiente_codigo(p_anio int)
returns text language plpgsql security definer set search_path = public as $$
declare n int;
begin
  insert into public.correlativos (anio, ultimo) values (p_anio, 1)
  on conflict (anio) do update set ultimo = correlativos.ultimo + 1
  returning ultimo into n;
  return format('EXP-%s-%s', case when n < 1000 then lpad(n::text, 3, '0') else n::text end, p_anio);
end $$;

create or replace function public.asignar_codigo()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.codigo is null or new.codigo = '' then
    new.codigo := public.siguiente_codigo(extract(year from now() at time zone 'America/Santiago')::int);
  end if;
  return new;
end $$;
drop trigger if exists antes_de_crear_expediente on public.expedientes;
create trigger antes_de_crear_expediente before insert on public.expedientes
  for each row execute function public.asignar_codigo();

-- Durante la importación de datos locales los triggers de checklist e historial no actúan
create or replace function public._importando()
returns boolean language sql stable as $$
  select coalesce(current_setting('expedientes.importando', true), '') = 'on'
$$;

-- ─── Al crear un expediente: copiar la plantilla al checklist ────────
create or replace function public.crear_checklist()
returns trigger language plpgsql security definer set search_path = public as $$
declare perfil public.profiles;
begin
  if public._importando() then return new; end if;
  select * into perfil from public.profiles where id = new.profesional_id;
  insert into public.expediente_items
    (expediente_id, requisito_id, orden, nombre, descripcion, opcional,
     cantidad_requerida, por_dueno, vence_en_dias, estado, cantidad_entregada, archivo_path)
  select new.id, r.id, r.orden, r.nombre, r.descripcion, r.opcional, r.cantidad, r.por_dueno, r.vence_en_dias,
         case when p.path is not null then 'listo' else 'pendiente' end,
         case when p.path is not null then r.cantidad else 0 end,
         p.path
  from public.requisitos_plantilla r
  left join lateral (select case r.origen_perfil when 'carnet' then perfil.carnet_path
                                                 when 'titulo' then perfil.titulo_path end as path) p on true
  where r.activo
  order by r.orden, r.id;
  insert into public.historial (expediente_id, usuario_id, accion) values (new.id, auth.uid(), 'Expediente creado');
  return new;
end $$;
drop trigger if exists al_crear_expediente on public.expedientes;
create trigger al_crear_expediente after insert on public.expedientes
  for each row execute function public.crear_checklist();

-- ─── Historial automático ────────────────────────────────────────────
create or replace function public.registrar_cambio_item()
returns trigger language plpgsql security definer set search_path = public as $$
declare cambios text[] := '{}';
begin
  if public._importando() then return new; end if;
  if new.estado is distinct from old.estado then
    cambios := cambios || format('estado: %s → %s', old.estado, new.estado);
  end if;
  if new.cantidad_entregada is distinct from old.cantidad_entregada then
    cambios := cambios || format('cantidad: %s/%s', new.cantidad_entregada, new.cantidad_requerida);
  end if;
  if new.fecha_emision is distinct from old.fecha_emision then
    cambios := cambios || format('emisión: %s', coalesce(new.fecha_emision::text, '—'));
  end if;
  if new.archivo_path is distinct from old.archivo_path then
    cambios := cambios || case when new.archivo_path is null then 'archivo quitado' else 'archivo adjuntado' end;
  end if;
  if new.comentario is distinct from old.comentario then
    cambios := cambios || 'comentario editado'::text;
  end if;
  if array_length(cambios, 1) > 0 then
    insert into public.historial (expediente_id, usuario_id, accion)
    values (new.expediente_id, auth.uid(), new.nombre || ' — ' || array_to_string(cambios, ', '));
  end if;
  return new;
end $$;
drop trigger if exists al_cambiar_item on public.expediente_items;
create trigger al_cambiar_item after update on public.expediente_items
  for each row execute function public.registrar_cambio_item();

create or replace function public.registrar_item_quitado()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  -- Si se borra el expediente completo no queda dónde anotarlo
  if exists (select 1 from public.expedientes where id = old.expediente_id) then
    insert into public.historial (expediente_id, usuario_id, accion)
    values (old.expediente_id, auth.uid(), old.nombre || ' — quitado del expediente');
  end if;
  return old;
end $$;
drop trigger if exists al_quitar_item on public.expediente_items;
create trigger al_quitar_item after delete on public.expediente_items
  for each row execute function public.registrar_item_quitado();

create or replace function public.registrar_cambio_expediente()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  new.updated_at := now();
  if new.estado is distinct from old.estado and not public._importando() then
    insert into public.historial (expediente_id, usuario_id, accion)
    values (new.id, auth.uid(), format('Estado del expediente: %s → %s', old.estado, new.estado));
  end if;
  return new;
end $$;
drop trigger if exists al_cambiar_expediente on public.expedientes;
create trigger al_cambiar_expediente before update on public.expedientes
  for each row execute function public.registrar_cambio_expediente();

-- ─── Importación de los datos locales (versión de escritorio 0.1.0) ──
-- 1) Usuarios: solo con la base sin usuarios. Todos con la misma contraseña temporal.
create or replace function public.importar_usuarios(p_usuarios jsonb, p_clave text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  u jsonb;
  mapa jsonb := '{}';
begin
  perform pg_advisory_xact_lock(hashtext('expedientes-usuarios'));
  if exists (select 1 from public.profiles) then raise exception 'Supabase ya tiene usuarios.'; end if;
  for u in select * from jsonb_array_elements(p_usuarios) loop
    mapa := mapa || jsonb_build_object(lower(trim(u ->> 'usuario')),
                                       public._crear_cuenta(u ->> 'usuario', u ->> 'nombre', p_clave));
  end loop;
  return mapa;
end $$;

-- Filas de un arreglo JSON como registros de la tabla, completando los valores por defecto
-- (jsonb_populate_recordset deja en nulo lo que no viene)
create or replace function public._filas(fila anyelement, arr jsonb, por_defecto jsonb)
returns setof anyelement language sql stable as $$
  select jsonb_populate_record(fila, por_defecto || e) from jsonb_array_elements(coalesce(arr, '[]')) e
$$;

-- 2) Datos: con la base sin expedientes. Conserva números, códigos, fechas e historial.
create or replace function public.importar_datos(p jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare t text;
begin
  if not public.es_miembro() then raise exception 'Sin permiso.'; end if;
  perform pg_advisory_xact_lock(hashtext('expedientes-importar'));
  if exists (select 1 from public.expedientes) then raise exception 'Supabase ya tiene expedientes.'; end if;
  perform set_config('expedientes.importando', 'on', true);

  -- La plantilla local reemplaza a la de Supabase (sin expedientes, nada la usa)
  -- («where true»: Supabase rechaza DELETE sin WHERE en llamadas desde la app)
  delete from public.requisitos_plantilla where true;
  insert into public.requisitos_plantilla overriding system value
    select * from public._filas(null::public.requisitos_plantilla, p -> 'requisitos',
      jsonb_build_object('created_at', now(), 'activo', true, 'opcional', false, 'por_dueno', false, 'cantidad', 1, 'orden', 0));
  insert into public.expedientes overriding system value
    select * from public._filas(null::public.expedientes, p -> 'expedientes',
      jsonb_build_object('created_at', now(), 'updated_at', now(), 'estado', 'borrador'));
  insert into public.duenos overriding system value
    select * from public._filas(null::public.duenos, p -> 'duenos', '{}');
  insert into public.expediente_items overriding system value
    select * from public._filas(null::public.expediente_items, p -> 'items',
      jsonb_build_object('estado', 'pendiente', 'cantidad_entregada', 0, 'cantidad_requerida', 1, 'opcional', false, 'por_dueno', false, 'orden', 0));
  insert into public.historial overriding system value
    select * from public._filas(null::public.historial, p -> 'historial', jsonb_build_object('created_at', now()));
  insert into public.correlativos (anio, ultimo)
    select anio, ultimo from jsonb_populate_recordset(null::public.correlativos, p -> 'correlativos')
  on conflict (anio) do update set ultimo = greatest(correlativos.ultimo, excluded.ultimo);
  update public.profiles pr set rut = x.rut, carnet_path = x.carnet_path, titulo_path = x.titulo_path, created_at = coalesce(x.created_at, pr.created_at)
    from jsonb_populate_recordset(null::public.profiles, p -> 'perfiles') x where pr.id = x.id;

  -- Los próximos registros siguen después de los importados
  foreach t in array array['requisitos_plantilla', 'expedientes', 'duenos', 'expediente_items', 'historial'] loop
    execute format('select setval(pg_get_serial_sequence(%L, ''id''), greatest((select coalesce(max(id), 0) from public.%I), 1), (select count(*) > 0 from public.%I))',
                   'public.' || t, t, t);
  end loop;

  return public.estado_base();
end $$;

