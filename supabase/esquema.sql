-- La primera versión usaba "generated always": se pasa a "by default" para poder
-- importar los datos locales conservando sus números (y las rutas de sus archivos)
do $$
declare t text;
begin
  foreach t in array array['requisitos_plantilla', 'expedientes', 'duenos', 'expediente_items', 'historial'] loop
    if exists (select 1 from information_schema.columns
               where table_schema = 'public' and table_name = t and column_name = 'id' and identity_generation = 'ALWAYS') then
      execute format('alter table public.%I alter column id set generated by default', t);
    end if;
  end loop;
end $$;

-- ─── Funciones de apoyo ──────────────────────────────────────────────
-- Miembro = cuenta con perfil activo. Es la única condición de acceso a los datos.
create or replace function public.es_miembro()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and activo)
$$;

-- Correo interno de cada usuario (no se envían correos: solo sirve para Supabase Auth).
-- La app calcula lo mismo en lib/usuarios.ts.
create or replace function public.correo_de(p_usuario text)
returns text language sql immutable set search_path = public, extensions as $$
  select case
    when lower(trim(p_usuario)) ~ '^[a-z0-9._-]{1,60}$' then lower(trim(p_usuario))
    else 'u-' || md5(lower(trim(p_usuario)))
  end || '@expedientes-spr.local'
$$;

-- Crea la cuenta en Supabase Auth (contraseña con bcrypt) y su perfil
create or replace function public._crear_cuenta(p_usuario text, p_nombre text, p_clave text)
returns uuid language plpgsql security definer set search_path = public, extensions, auth as $$
declare
  nuevo uuid := gen_random_uuid();
  usu text := lower(trim(p_usuario));
  correo text := public.correo_de(p_usuario);
begin
  if usu = '' or coalesce(trim(p_nombre), '') = '' then raise exception 'Falta el usuario o el nombre.'; end if;
  if length(p_clave) < 6 then raise exception 'La contraseña debe tener al menos 6 caracteres.'; end if;
  if exists (select 1 from public.profiles where lower(usuario) = usu) or exists (select 1 from auth.users where email = correo) then
    raise exception 'Ya existe un usuario con ese nombre de usuario.';
  end if;
  insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
                          raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
                          confirmation_token, recovery_token, email_change_token_new, email_change)
  values ('00000000-0000-0000-0000-000000000000', nuevo, 'authenticated', 'authenticated', correo,
          crypt(p_clave, gen_salt('bf')), now(),
          '{"provider":"email","providers":["email"]}', jsonb_build_object('usuario', usu, 'nombre', trim(p_nombre)),
          now(), now(), '', '', '', '');
  insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
  values (gen_random_uuid(), nuevo, nuevo::text,
          jsonb_build_object('sub', nuevo::text, 'email', correo, 'email_verified', true), 'email', now(), now(), now());
  insert into public.profiles (id, usuario, nombre) values (nuevo, usu, trim(p_nombre))
  on conflict (id) do update set usuario = excluded.usuario, nombre = excluded.nombre;
  return nuevo;
end $$;
revoke all on function public._crear_cuenta(text, text, text) from public, anon, authenticated;

-- Cuentas creadas desde el panel de Supabase: su perfil
create or replace function public.crear_perfil()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, usuario, nombre)
  values (new.id,
          lower(coalesce(new.raw_user_meta_data ->> 'usuario', split_part(new.email, '@', 1))),
          coalesce(new.raw_user_meta_data ->> 'nombre', split_part(new.email, '@', 1)))
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists al_crear_usuario on auth.users;
create trigger al_crear_usuario after insert on auth.users for each row execute function public.crear_perfil();

-- ─── Usuarios: primer uso, equipo y desactivación (nunca se borran) ──
create or replace function public.hay_usuarios()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles)
$$;

create or replace function public.estado_base()
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object('usuarios', (select count(*) from public.profiles),
                            'expedientes', (select count(*) from public.expedientes))
$$;

create or replace function public.crear_primer_usuario(p_usuario text, p_nombre text, p_clave text)
returns uuid language plpgsql security definer set search_path = public as $$
declare nuevo uuid;
begin
  perform pg_advisory_xact_lock(hashtext('expedientes-usuarios'));
  if exists (select 1 from public.profiles) then raise exception 'Ya existe un usuario. Ingresa con tu cuenta.'; end if;
  nuevo := public._crear_cuenta(p_usuario, p_nombre, p_clave);
  perform public._sembrar_plantilla();
  return nuevo;
end $$;

create or replace function public.crear_usuario(p_usuario text, p_nombre text, p_clave text)
returns uuid language plpgsql security definer set search_path = public as $$
begin
  if not public.es_miembro() then raise exception 'Sin permiso.'; end if;
  return public._crear_cuenta(p_usuario, p_nombre, p_clave);
end $$;

-- Quitar a alguien del equipo: se desactiva (no puede entrar) pero su nombre sigue en el historial
create or replace function public.desactivar_usuario(p_id uuid)
returns void language plpgsql security definer set search_path = public, auth as $$
begin
  if not public.es_miembro() then raise exception 'Sin permiso.'; end if;
  if p_id = auth.uid() then raise exception 'No puedes desactivar tu propio usuario.'; end if;
  update public.profiles set activo = false where id = p_id;
  update auth.users set banned_until = 'infinity' where id = p_id;
end $$;

create or replace function public.reactivar_usuario(p_id uuid)
returns void language plpgsql security definer set search_path = public, auth as $$
begin
  if not public.es_miembro() then raise exception 'Sin permiso.'; end if;
  update public.profiles set activo = true where id = p_id;
  update auth.users set banned_until = null where id = p_id;
end $$;

