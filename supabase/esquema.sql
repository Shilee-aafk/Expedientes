on conflict (id) do nothing;

do $$
declare pol record;
begin
  for pol in select policyname from pg_policies where schemaname = 'storage' and tablename = 'objects'
             and policyname in ('equipo lee documentos', 'equipo sube documentos', 'equipo reemplaza documentos',
                                'equipo borra documentos', 'miembros: documentos') loop
    execute format('drop policy %I on storage.objects', pol.policyname);
  end loop;
end $$;
